# 5. optimal_design.json (air-core design table)
# ---------------------------------------------------------------------------
SEC = "optimal_design.json"
path = os.path.join(config.OUTPUT_DIR, "optimal_design.json")
if os.path.exists(path):
    with open(path) as f:
        od = json.load(f)
    rec = od["recommended"]
    f_op = rec["f_kHz"] * 1e3
    w_op = 2 * math.pi * f_op
    a_od = rec["wire_radius_mm"] * 1e-3
    r_od = rec["coil_dia_mm"] / 2 * 1e-3
    ok_rows, n_rows = 0, 0
    # Every row must be internally consistent: L from the single-loop
    # formula, M from the N^2 anchor scaling, Cp the resonant capacitor
    # 1/(w^2 L), the capacitor peak voltage Ip*w*L within its rating, and the
    # open-circuit receiver voltage Vrx = w*M*Ip (Faraday).
    for row in od["table"]:
        n_rows += 1
        N = row["N"]
        L = row["L_mH"] * 1e-3
        M = row["M_uH"] * 1e-6
        good = (
            rel_err(L, loop_L(N, r_od, a_od)) < 0.01
            and rel_err(M, config.M0_H * (N / config.BASELINE_TURNS) ** 2) < 0.01
            and rel_err(row["Cp_nF"] * 1e-9, 1 / (w_op**2 * L)) < 0.01
            and rec["Ip_A"] * w_op * L <= row["Vcap"] * 1.001
            and rel_err(row["Vrx_oc_mV"] * 1e-3, w_op * M * rec["Ip_A"]) < 0.01
        )
        ok_rows += good
    check(SEC, "every row obeys L/M/C/Vcap/Vrx identities (1%)", ok_rows == n_rows,
          f"{ok_rows}/{n_rows} rows pass")
    check(SEC, "recommended row: cap voltage within its rating",
          rec["Ip_A"] * w_op * rec["L_mH"] * 1e-3 <= rec["Vcap"] * 1.001,
          f"V_cap = {rec['Ip_A'] * w_op * rec['L_mH'] * 1e-3:.0f} V vs {rec['Vcap']} V class")
    check(SEC, "recommended Q*Vrx_oc = Vrx_tuned (1%)",
          rel_err(rec["Vrx_tuned_V"], rec["Q"] * rec["Vrx_oc_mV"] * 1e-3) < 0.01)
else:
    skip(SEC, "all checks", "file missing")

