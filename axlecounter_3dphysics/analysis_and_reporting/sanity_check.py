"""
Physics sanity check for every report generated by this project.

Two layers of checking, both using ONLY basic electromagnetics -- no FEMM,
no rail, no fitted constants:

1. REFERENCE COIL MODEL. A bare air-core coil defined by inner radius ri,
   outer radius ro, axial length l and wire packing fraction:
     * turns from geometry:      N = pf * (ro-ri) * l / (pi * a_w^2)
     * inductance (Wheeler's multilayer formula, ~1-2% accurate) cross-checked
       against the single-loop formula used throughout this repo
     * DC + AC resistance (skin effect), quality factor Q = wL/R
     * resonant capacitor C = 1/(w^2 L) and its peak voltage V = Ip*w*L
     * coil-to-coil mutual inductance via the magnetic-dipole approximation
       for two coplanar (side-by-side) loops:  M = mu0*pi*N1*N2*r1^2*r2^2/(4 d^3)
   This gives order-of-magnitude expectations that any report must respect.

2. REPORT AUDITS. Each CSV/JSON in reports/ is checked against identities
   that must hold regardless of the model that produced it:
     * open-circuit induction:   V_rx = w * flux_rx           (AC FEMM rows)
     * linearity:                M independent of drive current
     * turn scaling:             M(N)/M(N0) = (N/N0)^2        (FEMM-verified law)
     * resonance:                C = 1/(w^2 L),  V_cap = Ip*w*L = Ip/(w*C)
     * detection dip arithmetic: dip% = (M0-M1)/M0
     * analytic outputs reproduce exactly from the config anchor
     * DOE optimum lies inside the sampled grid

Writes reports/sanity_check_report.md and exits non-zero if any check FAILS.
"""
